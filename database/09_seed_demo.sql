CREATE TEMP TABLE seed_map (key text PRIMARY KEY, id bigint NOT NULL) ON COMMIT DROP;

CREATE FUNCTION pg_temp.uid(p_email text) RETURNS bigint
LANGUAGE sql VOLATILE AS $$ SELECT user_id FROM campusfind.users WHERE email = p_email $$;

CREATE FUNCTION pg_temp.id(p_key text) RETURNS bigint
LANGUAGE plpgsql VOLATILE AS $$
DECLARE v bigint;
BEGIN
    SELECT id INTO v FROM seed_map WHERE key = p_key;
    IF v IS NULL THEN RAISE EXCEPTION 'seed key % not found', p_key; END IF;
    RETURN v;
END $$;

CREATE FUNCTION pg_temp.act_as(p_email text) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM set_config('app.user_id', pg_temp.uid(p_email)::text, true);
END $$;

CREATE FUNCTION pg_temp.add_item(
    p_key text, p_cat text, p_brand text, p_model text, p_colour text, p_size text, p_contents text,
    p_visible text, p_public text, p_loc text, p_loc_detail text, p_found_ago interval, p_storage text,
    p_serial text, p_hidden text,
    p_finder text, p_finder_contact text, p_finder_roll text, p_found_where text, p_circumstances text)
RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_id bigint;
    v_found timestamptz := now() - p_found_ago;
BEGIN
    INSERT INTO found_items (category_id, brand, model, colour_id, size_desc, contents, visible_marks,
                             public_description, found_location_id, found_location_detail, found_at,
                             storage_location, created_at)
    VALUES ((SELECT category_id FROM categories WHERE name = p_cat), p_brand, p_model,
            (SELECT colour_id FROM colours WHERE name = p_colour), p_size, p_contents, p_visible,
            p_public, (SELECT location_id FROM locations WHERE name = p_loc), p_loc_detail, v_found,
            p_storage, least(now(), v_found + interval '2 hours'))
    RETURNING item_id INTO v_id;

    IF p_serial IS NOT NULL OR p_hidden IS NOT NULL THEN
        INSERT INTO found_item_private (item_id, serial_no, hidden_marks)
        VALUES (v_id, p_serial, p_hidden);
    END IF;

    INSERT INTO finder_statements (item_id, finder_name, finder_contact, finder_roll_no,
                                   found_where, found_when, circumstances)
    VALUES (v_id, p_finder, p_finder_contact, p_finder_roll, p_found_where, v_found, p_circumstances);

    INSERT INTO item_photos (item_id, original_path, blurred_path, mime_type, size_bytes, is_primary)
    VALUES (v_id, 'originals/seed-' || lower(p_key) || '.jpg', 'blurred/seed-' || lower(p_key) || '.jpg',
            'image/jpeg', 60000, true);

    INSERT INTO seed_map VALUES (p_key, v_id);
    RETURN v_id;
END $$;

CREATE FUNCTION pg_temp.add_q(p_key text, p_question text, p_answer text) RETURNS void
LANGUAGE sql AS $$
    INSERT INTO campusfind.verification_questions (item_id, question_text, expected_answer)
    VALUES (pg_temp.id(p_key), p_question, p_answer);
$$;

CREATE FUNCTION pg_temp.add_report(
    p_key text, p_email text, p_cat text, p_brand text, p_model text, p_colour text,
    p_desc text, p_features text, p_serial text, p_loc text, p_loc_detail text,
    p_lost_ago interval, p_reported_after interval DEFAULT interval '3 hours')
RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE v_id bigint;
BEGIN
    INSERT INTO lost_reports (user_id, category_id, brand, model, colour_id, description, features,
                              serial_hint, lost_location_id, lost_location_detail, lost_at, created_at)
    VALUES (pg_temp.uid(p_email), (SELECT category_id FROM categories WHERE name = p_cat), p_brand, p_model,
            (SELECT colour_id FROM colours WHERE name = p_colour), p_desc, p_features, p_serial,
            (SELECT location_id FROM locations WHERE name = p_loc), p_loc_detail,
            now() - p_lost_ago, least(now(), now() - p_lost_ago + p_reported_after))
    RETURNING report_id INTO v_id;
    INSERT INTO seed_map VALUES (p_key, v_id);
    RETURN v_id;
END $$;

-- Submit a claim as the report's owner, answering the item's questions in order.
CREATE FUNCTION pg_temp.claim(p_claim_key text, p_report_key text, p_item_key text, p_answers text[] DEFAULT '{}')
RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
    v_owner bigint;
    v_answers jsonb;
    v_claim bigint;
BEGIN
    SELECT user_id INTO v_owner FROM lost_reports WHERE report_id = pg_temp.id(p_report_key);
    PERFORM set_config('app.user_id', v_owner::text, true);
    SELECT coalesce(jsonb_object_agg(q.question_id::text, p_answers[q.rn]), '{}'::jsonb) INTO v_answers
    FROM (SELECT question_id, row_number() OVER (ORDER BY question_id) AS rn
          FROM verification_questions WHERE item_id = pg_temp.id(p_item_key)) q;
    v_claim := submit_claim(pg_temp.id(p_report_key), pg_temp.id(p_item_key), v_answers);
    INSERT INTO seed_map VALUES (p_claim_key, v_claim);
    RETURN v_claim;
END $$;

